-- Monday of a show's week in a year.
create function public.salon_week(p_month int, p_dow int, p_nth int, p_year int)
returns date
language sql
immutable
set search_path = ''
as $$
  with a as (
    select make_date(p_year, p_month, 1)
           + ((p_dow - extract(isodow from make_date(p_year, p_month, 1))::int + 7) % 7)
           + (p_nth - 1) * 7 as anchor
  )
  select anchor - (extract(isodow from anchor)::int - 1) from a;
$$;

-- The show on this week (Paris), if any.
create function public.salon_now()
returns table (salon_id text, pack_id text, starts_on date, period text)
language sql
stable
set search_path = ''
as $$
  select s.id, s.pack_id, w.starts_on, s.id || ':' || to_char(w.starts_on, 'YYYY-MM-DD')
  from public.salons s
  cross join lateral (
    select public.salon_week(s.month, s.dow, s.nth, y) as starts_on
    from generate_series(extract(year from public.paris_today())::int - 1,
                         extract(year from public.paris_today())::int + 1) y
    where not s.even_years or y % 2 = 0
  ) w
  where public.paris_today() between w.starts_on and w.starts_on + 6
  limit 1;
$$;

-- This week's show challenges for a player; empty between shows.
create function public.salon_board(p_user uuid)
returns table (
  salon_id text,
  period text,
  ord smallint,
  kind text,
  param text,
  goal int,
  reward int,
  progress int,
  claimed boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select n.salon_id, n.period, c.ord, c.kind, c.param, c.goal, c.reward,
         least(public.mission_progress(p_user, c.kind, c.param,
                 n.starts_on::timestamp at time zone 'Europe/Paris'), c.goal),
         exists (
           select 1 from public.salon_claims sc
           where sc.user_id = p_user and sc.period = n.period and sc.ord = c.ord
         )
  from public.salon_now() n
  join public.salon_challenges c on c.salon_id = n.salon_id
  order by c.ord;
$$;

-- Finished and unclaimed: challenges, plus the finale once all are claimed or ready.
create function public.salon_ready(p_user uuid)
returns int
language sql
stable
security definer
set search_path = ''
as $$
  with b as (select * from public.salon_board(p_user))
  select (select count(*) from b where b.progress >= b.goal and not b.claimed)::int
       + case
           when exists (select 1 from b)
            and not exists (select 1 from b where b.progress < b.goal)
            and not exists (
              select 1 from public.salon_claims sc, b
              where sc.user_id = p_user and sc.period = b.period and sc.ord = 0
            )
           then 1 else 0
         end;
$$;

