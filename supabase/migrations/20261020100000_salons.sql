-- The show's week holds its anchor day: the nth ISO weekday `dow` of `month`.
-- even_years: held every other year (the Mondial).
create table public.salons (
  id text primary key,
  pack_id text not null unique references public.packs (id),
  month smallint not null check (month between 1 and 12),
  dow smallint not null check (dow between 1 and 7),
  nth smallint not null check (nth between 1 and 4),
  even_years boolean not null default false
);

-- Same kinds as missions, counted from the show's Monday.
create table public.salon_challenges (
  salon_id text not null references public.salons (id) on delete cascade,
  ord smallint not null check (ord > 0),
  kind text not null check (kind in ('open', 'open_pack', 'pull_tier', 'pull_trait', 'offer', 'trade', 'sell', 'buy', 'daily')),
  param text,
  goal int not null check (goal > 0),
  reward int not null check (reward > 0),
  primary key (salon_id, ord)
);

-- period: "<salon>:<monday>". ord 0 is the finale (every challenge claimed).
create table public.salon_claims (
  user_id uuid not null references auth.users (id) on delete cascade,
  period text not null,
  ord smallint not null,
  claimed_at timestamptz not null default now(),
  primary key (user_id, period, ord)
);

